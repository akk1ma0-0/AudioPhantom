/**
 * Generates docs/TARIFFS.md and docs/FEATURES_INFO.md from src/plans.ts + src/features-info.ts.
 * Usage: tsx scripts/generate-docs.ts [--check]   (--check fails if the files are stale)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import {
  EXTRA_HOURS_PACK,
  FEATURES,
  PLANS,
  PLAN_IDS,
  TRIAL,
  annualPriceCents,
  formatUsd,
} from '../src/plans.js';
import { FEATURES_INFO_EN } from '../src/features-info.js';

const docsDir = resolve(dirname(fileURLToPath(import.meta.url)), '../../../docs');
const BANNER =
  '<!-- GENERATED by packages/plans/scripts/generate-docs.ts - do not edit by hand. Run `pnpm docs:gen`. -->';

function tariffs(): string {
  const head = PLAN_IDS.map((p) => PLANS[p].name);
  const row = (cells: string[]) => `| ${cells.join(' | ')} |`;
  const lines = [
    BANNER,
    '',
    '# Plans and access',
    '',
    'Source of truth: `packages/plans/src/plans.ts`. Every feature carries an (i) icon; in Markdown it is the ⓘ link to the full explanation in [FEATURES_INFO.md](FEATURES_INFO.md). There is no free plan.',
    '',
    '## Prices (USD, excl. VAT)',
    '',
    row(['', ...head]),
    row(['---', ...head.map(() => '---')]),
    row(['Per month', ...PLAN_IDS.map((p) => formatUsd(PLANS[p].monthlyPriceCents))]),
    row(['Per year (10 months charged)', ...PLAN_IDS.map((p) => formatUsd(annualPriceCents(p)))]),
    '',
    `- Trial: ${TRIAL.hours} hours of live help within ${TRIAL.days} days, card required, ${PLANS[TRIAL.featuresOfPlan].name} features; auto-subscribes to the plan chosen at sign-up.`,
    `- Extra hours pack: ${EXTRA_HOURS_PACK.hours} h for ${formatUsd(EXTRA_HOURS_PACK.priceCents)}, on every plan.`,
    '',
    '## Features',
    '',
    'ⓘ = click for the full explanation. ✘ = not included (the explanation still says what it is and where it is available).',
    '',
    row(['Feature', ...head]),
    row(['---', ...head.map(() => '---')]),
  ];
  for (const f of FEATURES) {
    const cells = PLAN_IDS.map((p) => {
      const a = f.access[p];
      if (!a.included) return '✘';
      return a.value ? `✔ ${a.value}` : '✔';
    });
    lines.push(row([`[ⓘ](FEATURES_INFO.md#${f.id}) ${f.name}`, ...cells]));
  }
  lines.push('');
  return lines.join('\n');
}

function featuresInfo(): string {
  const lines = [
    BANNER,
    '',
    '# Feature explanations (the (i) icon texts)',
    '',
    'Source: `packages/plans/src/features-info.ts` (English i18n source strings; ru/ro fall back to English until translated). Back to [TARIFFS.md](TARIFFS.md).',
    '',
  ];
  for (const f of FEATURES) {
    lines.push(
      `<a id="${f.id}"></a>`,
      `### ⓘ ${f.name} (\`${f.id}\`)`,
      '',
      FEATURES_INFO_EN[f.id],
      '',
    );
  }
  return lines.join('\n');
}

const check = process.argv.includes('--check');
let stale = false;
for (const [name, content] of [
  ['TARIFFS.md', tariffs()],
  ['FEATURES_INFO.md', featuresInfo()],
] as const) {
  const path = resolve(docsDir, name);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`docs/${name} is stale; run \`pnpm docs:gen\``);
      stale = true;
    }
  } else {
    writeFileSync(path, content);
    console.log(`wrote docs/${name}`);
  }
}
if (stale) process.exit(1);
